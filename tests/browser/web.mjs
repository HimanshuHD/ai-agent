import assert from "node:assert/strict";
import { once } from "node:events";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { createWebServer } from "../../dist/web-server.js";
import { webLimits } from "../../dist/web-sessions.js";
import { createWorkspace } from "../../dist/workspace.js";
const root = await mkdtemp(path.join(os.tmpdir(), "agent-browser-"));
await mkdir(path.join(root, "src"));
await writeFile(path.join(root, "src/index.ts"), "export function startApplication() {}\nstartApplication();\n");
const original = globalThis.fetch;
globalThis.fetch = async (_url, options) => {
  const { messages } = JSON.parse(options.body);
  const prompt = messages.filter(message => message.role === "user").at(-1).content;
  const last = messages.at(-1);
  const text = content => Response.json({ message: { role: "assistant", content } });
  const tool = (name, args) => Response.json({ message: { role: "assistant", content: "Inspecting.", tool_calls: [{ function: { name, arguments: args } }] } });
  if (last.role === "tool") {
    const result = JSON.parse(last.content);
    if (result.matches) return tool("read_file", { path: result.matches[0].path, startLine: 1, endLine: 2 });
    if (result.path) return text("Startup is in src/index.ts:1-2.");
    if (result.utc) return text(`Current UTC: ${result.utc}`);
  }
  if (["slow", "timeout"].includes(prompt)) return new Promise((_resolve, reject) => options.signal.addEventListener("abort", () => reject(options.signal.reason), { once: true }));
  if (prompt === "fail") throw new TypeError("mock connection failed");
  if (prompt === "unsafe") return text("<img src=x onerror=\"window.__injected=1\">");
  if (prompt === "time") return tool("get_current_time", {});
  if (prompt === "inspect startup") return tool("search_text", { query: "startApplication" });
  return text(`Answer to: ${prompt}; context turns=${messages.filter(message => message.role === "user").length}`);
};
const app = createWebServer({ workspace: await createWorkspace(root), basePath: process.env.WEB_TEST_BASE_PATH, limits: { ...webLimits, runMs: 1500 } });
app.server.listen(Number(process.env.WEB_TEST_PORT ?? 0), "127.0.0.1");
await once(app.server, "listening");
const url = `http://127.0.0.1:${app.server.address().port}${process.env.WEB_TEST_BASE_PATH ?? "/"}`;
let browser;
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined, args: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? ["--no-sandbox", "--disable-gpu", "--no-zygote"] : [] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(url);
  await page.getByText("Backend connected", { exact: true }).waitFor();
  await page.screenshot({ path: path.join(os.tmpdir(), "agent-web-desktop.png"), fullPage: true });
  const prompt = page.getByRole("textbox", { name: "Message the local agent" });
  const send = async (text) => {
    await prompt.fill(text);
    await prompt.press("Enter");
    await page.locator(".turn").last().locator(".state:not(.running)").waitFor();
  };
  await send("hello");
  assert.match(await page.locator(".turn").last().innerText(), /context turns=1/);
  await send("follow-up");
  assert.match(await page.locator(".turn").last().innerText(), /context turns=2/);
  const other = await context.newPage();
  await other.goto(url);
  await other.getByText("Backend connected", { exact: true }).waitFor();
  await other.getByRole("textbox").fill("isolated");
  await other.getByRole("button", { name: "Send message" }).click();
  await other.locator(".state.completed").waitFor();
  assert.match(await other.locator(".answer-text").innerText(), /context turns=1/);
  await other.close();
  await page.getByRole("button", { name: "Reset conversation" }).click();
  await page.getByText("Start with a good question.").waitFor();
  assert.equal(await page.locator(".turn").count(), 0);
  await send("time");
  assert.match(await page.locator(".turn").last().innerText(), /get_current_time/);
  assert.match(await page.locator(".turn").last().innerText(), /Current UTC:/);
  await send("inspect startup");
  assert.match(await page.locator(".turn").last().innerText(), /search_text/);
  assert.match(await page.locator(".turn").last().innerText(), /read_file/);
  await send("unsafe");
  assert.match(await page.locator(".turn").last().innerText(), /<img src=x/);
  assert.equal(await page.locator(".answer img").count(), 0);
  assert.equal(await page.evaluate(() => window.__injected), undefined);
  await send("fail");
  assert.match(await page.locator(".turn").last().innerText(), /Could not connect to Ollama/);
  await prompt.fill("slow");
  await prompt.press("Enter");
  await page.getByRole("button", { name: "Cancel run", exact: true }).waitFor();
  assert.equal(await prompt.isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "Reset conversation" }).isDisabled(), true);
  await page.getByRole("button", { name: "Cancel run", exact: true }).click();
  await page.locator(".turn").last().locator(".state.cancelled").waitFor();
  await send("after cancellation");
  await send("timeout");
  assert.match(await page.locator(".turn").last().innerText(), /server deadline/);
  await prompt.fill("line one");
  await prompt.press("Shift+Enter");
  assert.equal(await prompt.inputValue(), "line one\n");
  await prompt.fill("");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(os.tmpdir(), "agent-web-mobile.png"), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  const retry = await context.newPage();
  await retry.route("**/api/sessions", route => route.abort());
  await retry.goto(url);
  await retry.getByRole("alert").waitFor();
  await retry.unroute("**/api/sessions");
  await retry.getByRole("button", { name: "Retry connection" }).click();
  await retry.getByText("Backend connected", { exact: true }).waitFor();
  console.log("Browser smoke passed: connection/retry, isolated follow-ups, reset, tool activity, safe text, failures, cancellation, timeout, keyboard, and mobile layout.");
}
finally {
  await browser?.close();
  globalThis.fetch = original;
  app.sessions.close();
  app.server.closeAllConnections();
  await new Promise(resolve => app.server.close(resolve));
  await rm(root, { recursive: true, force: true });
}
